def command_external(args):
    torch.set_num_threads(max(1,int(os.getenv("BLOCKAI_CPU_THREADS","2"))))
    workflows=load_real_workflows(args.source,args.input,args.limit)
    if not workflows: raise ValueError("No real workflow files found. Use 'download' first.")
    if args.inject_attacks:
        import numpy as np
        rng=np.random.default_rng(args.seed)
        # Deterministic per-run assignment: no original source attack labels.
        count=round(.3*len(workflows))
        indices=rng.choice(len(workflows),size=count,replace=False)
        for j,idx in enumerate(indices):
            workflows[idx]=inject_attack(workflows[idx],ATTACKS[j%len(ATTACKS)],rng)
    trainer=Trainer.load(args.model)
    predictions=trainer.predict(workflows)
    dest=Path(args.output);dest.mkdir(parents=True,exist_ok=True)
    save_json(dest/"predictions.json",predictions)
    if args.inject_attacks:
        report=report_metrics(workflows,predictions)
        save_json(dest/"evaluation.json",report)
        generate_figures(workflows,predictions,report,dest/"figures")
    manifest={"source":args.source,"n":len(workflows),"attacks_are_injected":bool(args.inject_attacks),
              "metadata_only_artifact_hashing":True,"openml_dag_inferred":args.source=="openml",
              "note":"No native attacks or verified artifact hashes exist in the source files"}
    save_json(dest/"evaluation_protocol.json",manifest)
    print(json.dumps({"output":str(dest),**manifest},indent=2))


def command_ledger(args):
    workflows=load_workflows(args.input,limit=args.limit)
    dest=Path(args.output);dest.mkdir(parents=True,exist_ok=True)
    if args.backend=="simulated":
        backend=SimulatedLedger(block_size=args.block_size)
        for wf in workflows:backend.process(wf)
        backend.finalize()
        result=backend.statistics()
        backend.export(dest/"simulated_ledger.json")
    else:
        backend=FabricGatewayLedger(args.gateway)
        status=backend.health()
        records=[]
        before=time.perf_counter()
        for wf in workflows:
            records.append(backend.replay(wf,store_private=args.store_private))
        dt=time.perf_counter()-before
        passed=sum(r["accepted"] for wf in records for r in wf["attempts"])
        count=sum(len(wf["attempts"]) for wf in records)
        result={"backend":"hyperledger_fabric","attempted":count,"accepted":passed,
                "rejected":count-passed,"elapsed_seconds":dt,"committed_tps":passed/max(dt,1e-6),
                "gateway_health":status,
                "note":"Client-observed wall time; collect peer-side commit metrics separately"}
        save_json(dest/"fabric_replay.json",records)
    save_json(dest/"ledger_summary.json",result)
    print(json.dumps(result,indent=2))


def command_audit(args):
    workflows=load_workflows(args.input,limit=args.limit)
    trainer=Trainer.load(args.model) if args.model else None
    predictions=trainer.predict(workflows) if trainer else []
    lookup={p["workflow_id"]:p for p in predictions}
    ledger=SimulatedLedger()
    audited=[]
    for wf in workflows:
        ledger.process(wf)
        ledger.finalize()  # Audit only after actual simulated block commitment.
        pred=lookup.get(wf.workflow_id,{})
        audited.append(audit_workflow(wf,ledger,pred.get("step_probabilities"),bool(pred.get("predicted",0))).to_dict())
    ledger.finalize()
    save_json(args.output,{"simulated":True,"results":audited,"ledger":ledger.statistics()})
    print(json.dumps({"audits":len(audited),"output":args.output},indent=2))


def command_ablation(args):
    torch.set_num_threads(max(1,int(os.getenv("BLOCKAI_CPU_THREADS","2"))))
    dataset=load_workflows(args.input)
    cfg=_config(args.config)
    configurations={
        "full":{}, "without_gat":{"gat_layers":0},
        "without_gru":{"use_gru":False}, "without_integrity":{"use_integrity":False},
        "without_actor":{"use_actor":False}, "without_temporal":{"use_temporal":False},
    }
    dest=Path(args.output);dest.mkdir(parents=True,exist_ok=True)
    train,val,test=split_workflows(dataset,args.seed)
    scores={}
    for name,changes in configurations.items():
        params=_train_config(cfg,args.seed,args.epochs)
        for key,value in changes.items():setattr(params,key,value)
        trainer=Trainer(params)
        trainer.train(train,val)
        pred=trainer.predict(test)
        scores[name]=report_metrics(test,pred)["overall"]
        trainer.save(dest/name)
        save_json(dest/f"{name}_predictions.json",pred)
    save_json(dest/"ablations.json",scores)
    print(json.dumps({k:round(v["f1"],4) for k,v in scores.items()},indent=2))



def command_tune(args):
    """Optuna TPE selection on TRAIN+VALIDATION only; test evaluated once."""
    try: import optuna
    except ImportError as exc: raise RuntimeError("pip install 'blockai-fusion[experiments]' to run Optuna") from exc
    torch.set_num_threads(max(1,int(os.getenv("BLOCKAI_CPU_THREADS","2"))))
    dataset=load_workflows(args.input)
    cfg=_config(args.config)
    train,val,test=split_workflows(dataset,args.seed,args.protocol,args.held_out_attack)
    dest=Path(args.output);dest.mkdir(parents=True,exist_ok=True)
    best_model=None
    def objective(trial):
        params=_train_config(cfg,args.seed,epochs=args.epochs)
        params.gru_hidden=trial.suggest_categorical("gru_hidden",[64,128,256])
        params.gat_layers=trial.suggest_categorical("gat_layers",[1,2,3])
        params.gat_heads=trial.suggest_categorical("gat_heads",[2,4,8])
        params.dropout=trial.suggest_categorical("dropout",[.1,.3,.5])
        params.learning_rate=trial.suggest_categorical("learning_rate",[1e-4,5e-4,1e-3,3e-3])
        trainer=Trainer(params)
        result=trainer.train(train,val)
        return float(result["best_val_pr_auc"])
    sampler=optuna.samplers.TPESampler(seed=args.seed)
    study=optuna.create_study(direction="maximize",sampler=sampler)
    study.optimize(objective,n_trials=args.trials,show_progress_bar=False)
    selected=_train_config(cfg,args.seed,epochs=args.epochs)
    for key,value in study.best_params.items():setattr(selected,key,value)
    trainer=Trainer(selected)
    training=trainer.train(train,val)
    predictions=trainer.predict(test)
    reported=report_metrics(test,predictions)
    trainer.save(dest/"best_model")
    save_json(dest/"tuning.json",{
        "trials":args.trials,"best_validation_pr_auc":study.best_value,
        "best_parameters":study.best_params,"random_seed":args.seed,
        "evaluation_protocol":args.protocol,"held_out_attack":args.held_out_attack,
        "data_splits":{"train":len(train),"validation":len(val),"test":len(test)},
        "retrained_best_configuration":training,
        "final_test_evaluated_once":reported})
    save_json(dest/"predictions.json",predictions)
    study.trials_dataframe().to_csv(dest/"optuna_trials.csv",index=False)
    generate_figures(test,predictions,reported,dest/"figures")
    print(json.dumps({"best_config":study.best_params,"validation_pr_auc":study.best_value,
                      "test":reported["overall"],"output":str(dest)},indent=2))

def command_repeats(args):
    torch.set_num_threads(max(1,int(os.getenv("BLOCKAI_CPU_THREADS","2"))))
    cfg=_config(args.config)
    seeds=cfg.get("seeds",[42,11,23,37,58,61,77,89,97,101])
    root=Path(args.output);root.mkdir(parents=True,exist_ok=True)
    f1s={"ProvSeqGAT":[]}
    metric_runs=[]
    for seed in seeds:
        if args.input:
            dataset=load_workflows(args.input)
        else:
            dataset=make_dataset(int(cfg.get("n_workflows",10000)),seed,
                                 attack_fraction=float(cfg.get("attack_fraction",.3)))
        report=experiment(dataset,root/f"seed_{seed}",seed,cfg,epochs=args.epochs,
                          baselines=args.baselines)
        f1s["ProvSeqGAT"].append(report["metrics"]["overall"]["f1"])
        metric_runs.append(report["metrics"]["overall"])
        for name,baseline in report.get("baselines",{}).items():
            f1s.setdefault(name,[]).append(baseline["f1"])
    if not args.baselines: paired={}
    else: paired=compare_paired_runs(f1s)
    from scipy import stats
    metric_stats={}
    for key in ("accuracy","precision","recall","f1","far","pr_auc","roc_auc","step_f1"):
        values=np.array([r.get(key,np.nan) for r in metric_runs],dtype=float)
        values=values[np.isfinite(values)]
        if not len(values): continue
        mean=float(values.mean());std=float(values.std(ddof=1)) if len(values)>1 else 0.
        low,high=stats.t.interval(.95,len(values)-1,loc=mean,scale=std/np.sqrt(len(values))) if len(values)>1 and std else (mean,mean)
        metric_stats[key]={"mean":mean,"std":std,"95ci":[float(low),float(high)]}
    summary={"seeds":seeds,"metric_summary":metric_stats,"f1_mean_std":{k:{"mean":float(np.mean(v)),
               "std":float(np.std(v,ddof=1)) if len(v)>1 else 0} for k,v in f1s.items()},
             "paired_comparison":paired}
    save_json(root/"repetitions_summary.json",summary)
    print(json.dumps(summary,indent=2))



def command_artifact_store(args):
    from .provenance import EncryptedArtifactStore
    import secrets
    root=Path(args.output);root.mkdir(parents=True,exist_ok=True)
    key_path=Path(args.key_file)
    if key_path.exists():
        key=bytes.fromhex(key_path.read_text().strip())
    else:
        key=secrets.token_bytes(32)
        key_path.parent.mkdir(parents=True,exist_ok=True)
        fd=os.open(str(key_path),os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
        with os.fdopen(fd,"w") as f:f.write(key.hex()+"\n")
    store=EncryptedArtifactStore(root,key)
    workflows=load_workflows(args.input,limit=args.limit)
    manifest=[]
    for wf in workflows:
        for step in wf.steps:
            digest=store.write(step.artifact)
            manifest.append({"workflow_id":wf.workflow_id,"step_id":step.step_id,"artifact_digest":digest})
    save_json(root/"artifact_manifest.json",manifest)
    print(json.dumps({"encrypted_artifacts":len(manifest),"output":str(root),
                      "private_key_file":str(key_path),"warning":"Keep the key outside the repository and retain a secure backup"},indent=2))


def command_governance(args):
    torch.set_num_threads(max(1,int(os.getenv("BLOCKAI_CPU_THREADS","2"))))
    workflows=load_workflows(args.input,limit=100)
    if not workflows: raise ValueError("No workflows")
    # Start with a valid workflow by default, so the feedback mechanism is
    # visible rather than all later children being rejected after a corrupted root.
    wf=next((x for x in workflows if x.label==0),workflows[0]) if not args.include_attacked else workflows[0]
    trainer=Trainer.load(args.model)
    ledger=SimulatedLedger()
    history=[]
    for i,step in enumerate(wf.steps):
        if args.auto_audit and ledger._trust.get(wf.workflow_id,1)<.55:
            ledger.approve_next_step(wf.workflow_id,step.step_id)
        attempt=ledger.submit(wf,step)
        prefix=type(wf).from_dict(wf.to_dict())
        prefix.steps=prefix.steps[:i+1]
        prefix.expected_step_ids=[s.step_id for s in prefix.steps]
        p=trainer.predict([prefix])[0]["anomaly_probability"]
        from .trust import workflow_trust,integrity_fraction
        trust=workflow_trust(p,integrity_fraction(prefix),.8)
        ledger.set_trust(wf.workflow_id,trust)
        history.append({"step_id":step.step_id,"accepted":attempt.accepted,
                        "anomaly_probability":p,"trust":trust,
                        "requires_auditor_next":trust<.55})
    ledger.finalize()
    save_json(args.output,{"backend":"simulated_not_fabric","history":history,
                           "ledger":ledger.statistics(),"auto_audit":args.auto_audit,
                           "warning":"Prefix scoring is a demonstration and is not independently calibrated for early-event detection"})
    print(json.dumps({"steps":len(history),"accepted":sum(h["accepted"] for h in history),
                      "output":args.output},indent=2))

