def _config(path):
    if not path: return {}
    with open(path,encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def _train_config(cfg: dict,seed: int,epochs: int | None = None) -> TrainConfig:
    return TrainConfig(seed=seed,epochs=epochs or cfg.get("epochs",100),
                       patience=cfg.get("patience",10),
                       batch_size=cfg.get("batch_size",64),
                       learning_rate=cfg.get("learning_rate",1e-3),
                       dropout=cfg.get("dropout",.3),
                       gru_hidden=cfg.get("model_hidden_size",64),
                       gat_heads=cfg.get("num_gat_heads",4),
                       gat_layers=cfg.get("num_gat_layers",2),
                       warmup_epochs=cfg.get("warmup_epochs",5))


def experiment(workflows, output: str | Path, seed: int, cfg: dict,
               protocol: str="random", held_out_attack: str | None=None,
               epochs: int | None=None, baselines: bool=False,
               quick: bool=False) -> dict:
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    train,val,test=split_workflows(workflows,seed,protocol,held_out_attack)
    trainer=Trainer(_train_config(cfg,seed,epochs))
    start=time.perf_counter()
    training_info=trainer.train(train,val)
    predictions=trainer.predict(test)
    report=report_metrics(test,predictions)
    intervals=bootstrap_confidence_intervals(test,predictions,reps=200 if quick else 1000,seed=seed)
    trust=score_batch_chronologically(list(test),predictions)
    result={"project":"Blockchain-AI Fusion","run_seed":seed,"protocol":protocol,
            "held_out_attack":held_out_attack,"split":{"train":len(train),"validation":len(val),"test":len(test)},
            "training":training_info,"metrics":report,"bootstrap_95ci":intervals,
            "runtime_seconds":round(time.perf_counter()-start,3),
            "trust":{"mean_score":float(np.mean([x["trust_score"] for x in trust])),
                     "auditor_required":int(sum(x["requires_auditor"] for x in trust))},
            "provenance":"results generated by execution, not copied from manuscript"}
    trainer.save(output/"model")
    save_json(output/"results.json",result)
    save_json(output/"predictions.json",predictions)
    save_json(output/"trust_scores.json",trust)
    if baselines:
        compared=run_baselines(train,val,test,trainer.encoder,seed,quick=quick)
        result["baselines"]={name:v["metrics"] for name,v in compared.items()}
        save_json(output/"baseline_predictions.json",compared)
        save_json(output/"results.json",result)
    generate_figures(test,predictions,report,output/"figures")
    return result


def command_smoke(args):
    default_config=Path(__file__).resolve().parents[2]/"configs/smoke.yaml"
    cfg=_config(args.config) if args.config else (_config(default_config) if default_config.exists() else {
        "n_workflows":96,"attack_fraction":.30,"min_steps":5,"max_steps":22,
        "batch_size":8,"epochs":3,"patience":2})
    count=args.n or int(cfg.get("n_workflows",96))
    torch.set_num_threads(max(1,int(os.getenv("BLOCKAI_CPU_THREADS","2"))))
    workflows=make_dataset(count,args.seed,attack_fraction=float(cfg.get("attack_fraction",.3)),
                           min_steps=int(cfg.get("min_steps",5)),max_steps=int(cfg.get("max_steps",22)))
    dest=Path(args.output)
    save_workflows(workflows,dest/"synthetic_workflows.jsonl.gz")
    res=experiment(workflows,dest,args.seed,cfg,epochs=args.epochs or int(cfg.get("epochs",3)),
                   baselines=not args.skip_baselines,quick=True)
    sim=SimulatedLedger(block_size=20)
    _,_,test=split_workflows(workflows,args.seed)
    for wf in test:sim.process(wf)
    sim.finalize();sim.export(dest/"simulated_ledger.json")
    res["local_ledger_simulation"]=sim.statistics()
    save_json(dest/"results.json",res)
    print(json.dumps({"output":str(dest.resolve()),"metrics":res["metrics"]["overall"],
                      "ledger":res["local_ledger_simulation"],"validation":res["training"]},indent=2))


